// escapeFixture writes a garden whose every author-supplied string carries a
// double quote and an angle bracket, then builds it.
func escapeFixture(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	page := "---\n" +
		"title: 'He said \"hi\" <b>'\n" +
		"description: 'A \"quoted\" <em>summary</em>'\n" +
		"---\n\n" +
		"Body text.\n"
	if err := os.WriteFile(filepath.Join(dir, "note.md"), []byte(page), 0644); err != nil {
		t.Fatal(err)
	}
	t.Chdir(dir)

	cfg := config.Default()
	cfg.Site.Title = `Shivam's "Garden" <script>`
	cfg.Site.Description = `A garden of "notes" & <ideas>`
	cfg.Site.Author = `A "B" <c>`
	cfg.Site.BaseURL = "https://example.com"
	cfg.Features.RSS = true
	cfg.Navigation.Mode = config.NavExplicit
	cfg.Navigation.Items = []config.NavItem{{Label: `Home "x"`, Path: `/"onmouseover=alert(1)`}}

	if _, err := New(cfg, Options{}).Build(); err != nil {
		t.Fatal(err)
	}
	return filepath.Join(dir, "_site")
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

// A raw quote inside content="..." closes the attribute early, so the OG tag
// silently loses its tail. That is a functional SEO bug before it is an XSS.
func TestBuildEscapesSiteAndPageMetaInMarkup(t *testing.T) {
	siteDir := escapeFixture(t)

	for _, rel := range []string{"note/index.html", "index.html", "404.html"} {
		path := filepath.Join(siteDir, filepath.FromSlash(rel))
		if _, err := os.Stat(path); os.IsNotExist(err) {
			continue
		}
		html := readFile(t, path)
		for _, raw := range []string{
			`content="A garden of "notes"`,
			`content="A "quoted"`,
			`content="He said "hi"`,
			`Garden" <script>`,
			`"onmouseover=alert(1)`,
		} {
			if strings.Contains(html, raw) {
				t.Errorf("%s leaks unescaped author text %q", rel, raw)
			}
		}
	}

	note := readFile(t, filepath.Join(siteDir, "note", "index.html"))
	if !strings.Contains(note, "&#34;quoted&#34;") {
		t.Errorf("page description was not escaped:\n%s", note)
	}
	if !strings.Contains(note, "&#34;hi&#34;") {
		t.Errorf("page title was not escaped:\n%s", note)
	}
}

// Auto-generated descriptions round-trip through PlainContent, which
// un-escapes entities. Without an explicit pin they re-enter a meta attribute
// raw even though the frontmatter never set a description.
func TestBuildEscapesAutoGeneratedDescription(t *testing.T) {
	dir := t.TempDir()
	// Typographer rewrites straight quotes, so probe with < and & instead:
	// both survive rendering and both break a meta attribute if unescaped.
	body := "---\ntitle: Plain\n---\n\nWhen 5 < 6 & the tag </meta> appears.\n"
	if err := os.WriteFile(filepath.Join(dir, "note.md"), []byte(body), 0644); err != nil {
		t.Fatal(err)
	}
	t.Chdir(dir)
	if _, err := New(config.Default(), Options{}).Build(); err != nil {
		t.Fatal(err)
	}

	html := readFile(t, filepath.Join(dir, "_site", "note", "index.html"))
	descAt := strings.Index(html, `<meta name="description" content="`)
	if descAt < 0 {
		t.Fatalf("no description meta tag:\n%s", html)
	}
	desc := html[descAt+len(`<meta name="description" content="`):]
	desc = desc[:strings.Index(desc, `">`)]
	if strings.ContainsAny(desc, `<&"`[:1]) || strings.Contains(desc, "</meta>") {
		t.Errorf("auto description leaked raw markup into a meta attribute: %q", desc)
	}
	if !strings.Contains(desc, "&lt;") || !strings.Contains(desc, "&amp;") {
		t.Errorf("auto description was not escaped: %q", desc)
	}
}

// RSS and the JSON indexes carry their own encoding, so they must receive the
// text the author actually typed — not the HTML-escaped spelling.
func TestBuildArtifactsCarryUnescapedText(t *testing.T) {
	siteDir := escapeFixture(t)

	feed := readFile(t, filepath.Join(siteDir, "feed.xml"))
	if strings.Contains(feed, "&amp;#34;") {
		t.Errorf("feed.xml double-encoded an escaped quote:\n%s", feed)
	}

	var index []struct {
		Title string `json:"title"`
	}
	raw := readFile(t, filepath.Join(siteDir, "search-index.json"))
	if err := json.Unmarshal([]byte(raw), &index); err != nil {
		t.Fatalf("search-index.json is not the expected array: %v\n%s", err, raw)
	}
	var found bool
	for _, entry := range index {
		if entry.Title == `He said "hi" <b>` {
			found = true
		}
		if strings.Contains(entry.Title, "&#34;") {
			t.Errorf("search index carries an HTML-escaped title: %q", entry.Title)
		}
	}
	if !found {
		t.Errorf("search index lost the raw page title; got %+v", index)
	}
}

// Escaping titles must not break title-form wikilinks: the alias map holds
// both spellings, so [[Q&A]] still resolves after Q&A became Q&amp;A.
func TestBuildResolvesTitleWikilinkWithEscapableTitle(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "q-and-a.md"), []byte("---\ntitle: Q&A\n---\n\nAnswers.\n"), 0644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "note.md"), []byte("---\ntitle: Note\n---\n\nSee [[Q&A]].\n"), 0644); err != nil {
		t.Fatal(err)
	}
	t.Chdir(dir)

	cfg := config.Default()
	cfg.Features.Wikilinks = true
	if _, err := New(cfg, Options{}).Build(); err != nil {
		t.Fatal(err)
	}

	html := readFile(t, filepath.Join(dir, "_site", "note", "index.html"))
	if !strings.Contains(html, `href="/q-and-a/"`) {
		t.Errorf("[[Q&A]] did not resolve to the escapable-titled page:\n%s", html)
	}
}
